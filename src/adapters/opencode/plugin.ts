// The opencode plugin file `openmorals init --agent opencode` writes. It is plain JavaScript with no imports beyond
// node:child_process, so it loads in opencode without installing anything into the project. It exports one object
// carrying both plugin APIs: `id` + `setup(ctx)` for V2 and `server(input)` for V1 (documented "Support V1" form).

export const PLUGIN_MARKER = '// openmorals opencode plugin';

export function pluginSource(command: readonly string[]): string {
  return `${PLUGIN_MARKER}, format 1. Generated by \`openmorals init --agent opencode\`; running init again replaces this file.
// Every tool call is sent to openmorals, which answers from openmorals.yaml. If openmorals cannot answer, the call is
// blocked (or, in a V2 permission check, asked about). Remove this file to switch openmorals off for opencode.
import { spawn } from "node:child_process";

const COMMAND = ${JSON.stringify(command)};
const TIMEOUT_MS = 30000;
const UNAVAILABLE = "openmorals could not judge this call (is the openmorals command installed and on PATH?), so it is blocked";
const UNAVAILABLE_ASK = "openmorals could not judge this request (is the openmorals command installed and on PATH?), so it asks";

function consult(payload) {
  return new Promise((resolve) => {
    let child;
    try {
      child = spawn(COMMAND[0], COMMAND.slice(1), { stdio: ["pipe", "pipe", "ignore"], windowsHide: true, shell: process.platform === "win32" });
    } catch {
      resolve(null);
      return;
    }
    let out = "";
    let settled = false;
    const finish = (value) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve(value);
    };
    const timer = setTimeout(() => {
      try {
        child.kill();
      } catch {}
      finish(null);
    }, TIMEOUT_MS);
    child.on("error", () => finish(null));
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk) => {
      out += chunk;
    });
    child.on("close", (code) => {
      if (code !== 0) return finish(null);
      try {
        const answer = JSON.parse(out);
        finish(answer !== null && typeof answer === "object" ? answer : null);
      } catch {
        finish(null);
      }
    });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify(payload));
  });
}

function textOf(answer, fallback) {
  return typeof answer.message === "string" && answer.message !== "" ? answer.message : fallback;
}

async function before(api, sessionID, callID, tool, args, cwd) {
  const answer = await consult({ event: "tool.execute.before", api, sessionID: sessionID ?? null, callID: callID ?? null, tool: String(tool), args: args ?? null, cwd });
  if (answer === null) throw new Error(UNAVAILABLE);
  if (answer.block !== false) throw new Error(textOf(answer, "blocked by openmorals"));
}

async function evaluate(event, cwd) {
  if (event.effect === "deny") return;
  const resources = Array.isArray(event.resources) ? event.resources.filter((r) => typeof r === "string") : [];
  const answer = await consult({ event: "permission.evaluate", sessionID: event.sessionID ?? null, action: String(event.action), resources, effect: event.effect, cwd });
  if (answer === null) {
    event.effect = "ask";
    event.message = UNAVAILABLE_ASK;
    return;
  }
  if (answer.effect === "deny" || answer.effect === "ask") {
    event.effect = answer.effect;
    event.message = textOf(answer, "openmorals");
  } else if (answer.effect !== "allow") {
    event.effect = "ask";
    event.message = UNAVAILABLE_ASK;
  }
}

export default {
  id: "openmorals",
  async setup(ctx) {
    const cwd = (ctx && ctx.location && ctx.location.directory) || process.cwd();
    await ctx.tool.hook("execute.before", (event) => before("v2", event.sessionID, event.callID, event.tool, event.input, cwd));
    await ctx.permission.hook("evaluate", (event) => evaluate(event, cwd));
  },
  async server(input) {
    const cwd = (input && input.directory) || process.cwd();
    return {
      "tool.execute.before": async (hookInput, output) => before("v1", hookInput && hookInput.sessionID, hookInput && hookInput.callID, hookInput && hookInput.tool, output && output.args, cwd),
    };
  },
};
`;
}

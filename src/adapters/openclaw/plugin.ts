// The OpenClaw plugin `openmorals init --agent openclaw` writes: a folder with the manifest OpenClaw requires
// (openclaw.plugin.json: id and configSchema), a package.json pointing `openclaw.extensions` at index.js, and index.js,
// plain JavaScript with no imports beyond node:child_process. It default-exports the same object shape
// `definePluginEntry` returns ({ id, name, description, configSchema, register }), so it needs no SDK import.

export const OPENCLAW_PLUGIN_MARKER = '// openmorals openclaw plugin';
export const OPENCLAW_PLUGIN_DIR = '.openclaw/plugins/openmorals';

export function openclawIndexSource(command: readonly string[], projectDir: string): string {
  return `${OPENCLAW_PLUGIN_MARKER}, format 3. Generated by \`openmorals init --agent openclaw\`; running init again replaces this file.
// Every tool call is sent to openmorals, which answers from openmorals.yaml: nothing (allow), an approval request (ask)
// or a block (deny). If openmorals cannot answer, the call is blocked. OpenClaw blocks the call too if this hook throws
// or times out. If openmorals cannot record a call's result or a turn's tokens, the session's next call asks, and keeps
// asking until openmorals confirms it has stored the mark.
// Remove the plugin (openclaw plugins uninstall openmorals) to switch openmorals off for OpenClaw.
import { spawn } from "node:child_process";

const COMMAND = ${JSON.stringify(command)};
const PROJECT = ${JSON.stringify(projectDir)};
const TIMEOUT_MS = 25000;
const UNAVAILABLE = "openmorals could not judge this call (is the openmorals command installed and on PATH?), so it is blocked";
// after_tool_call and llm_output only observe, so a failure there cannot block anything. It is kept here, per session,
// and sent with that session's next before_tool_call, which then asks (and marks the session as having read untrusted content).
// An entry is removed only when openmorals answers missedTaken, which it does only after the mark is saved; entries are
// removed by identity, so a miss added while a call is in flight is never removed by another call's answer.
const MISSED = new Map();
const MISSED_SESSIONS = 256;
const MISSED_EVENTS = 64;

function remember(session, entry) {
  const key = session === null ? "" : session;
  const list = MISSED.get(key) || [];
  if (list.length < MISSED_EVENTS) list.push(entry);
  MISSED.delete(key);
  MISSED.set(key, list);
  if (MISSED.size > MISSED_SESSIONS) MISSED.delete(MISSED.keys().next().value);
}

function delivered(answer) {
  return answer !== null && answer.rule !== "hook.observe-error";
}

function consult(payload) {
  return new Promise((resolve) => {
    let child;
    try {
      child = spawn(COMMAND[0], COMMAND.slice(1), { stdio: ["pipe", "pipe", "ignore"], windowsHide: true, shell: process.platform === "win32" });
    } catch {
      resolve(null);
      return;
    }
    let out = "";
    let settled = false;
    const finish = (value) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve(value);
    };
    const timer = setTimeout(() => {
      try {
        child.kill();
      } catch {}
      finish(null);
    }, TIMEOUT_MS);
    child.on("error", () => finish(null));
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk) => {
      out += chunk;
    });
    child.on("close", (code) => {
      if (code !== 0) return finish(null);
      try {
        const answer = JSON.parse(out);
        finish(answer !== null && typeof answer === "object" ? answer : null);
      } catch {
        finish(null);
      }
    });
    child.stdin.on("error", () => {});
    child.stdin.end(JSON.stringify(payload));
  });
}

function sessionOf(event, ctx) {
  if (event && typeof event.sessionId === "string" && event.sessionId !== "") return event.sessionId;
  if (ctx && typeof ctx.sessionId === "string" && ctx.sessionId !== "") return ctx.sessionId;
  if (ctx && typeof ctx.sessionKey === "string" && ctx.sessionKey !== "") return ctx.sessionKey;
  return null;
}

function agentOf(ctx) {
  return ctx && typeof ctx.agentId === "string" && ctx.agentId !== "" ? ctx.agentId : null;
}

function resultText(result) {
  if (typeof result === "string") return result;
  if (!result || typeof result !== "object") return null;
  if (Array.isArray(result.content)) {
    const parts = result.content.filter((p) => p && typeof p.text === "string").map((p) => p.text);
    return parts.length > 0 ? parts.join("\\n") : null;
  }
  if (typeof result.content === "string") return result.content;
  if (typeof result.output === "string") return result.output;
  return null;
}

async function beforeToolCall(event, ctx) {
  const session = sessionOf(null, ctx);
  const key = session === null ? "" : session;
  const pending = MISSED.get(key);
  const sent = pending !== undefined && pending.length > 0 ? pending.slice() : undefined;
  const missed = sent !== undefined ? sent.map((m) => ({ event: m.event, ...(m.toolName !== undefined ? { toolName: m.toolName } : {}) })) : undefined;
  const answer = await consult({
    event: "before_tool_call",
    toolName: String(event && event.toolName),
    params: event && event.params ? event.params : null,
    toolCallId: (event && event.toolCallId) || (ctx && ctx.toolCallId) || null,
    derivedPaths: event && Array.isArray(event.derivedPaths) ? event.derivedPaths.filter((p) => typeof p === "string") : [],
    sessionId: sessionOf(null, ctx),
    agentId: agentOf(ctx),
    cwd: PROJECT,
    ...(missed !== undefined ? { missed } : {}),
  });
  if (answer === null) return { block: true, blockReason: UNAVAILABLE };
  const taken = sent !== undefined && Number.isInteger(answer.missedTaken) && answer.missedTaken > 0 ? sent.slice(0, answer.missedTaken) : [];
  if (taken.length > 0) {
    const now = MISSED.get(key);
    if (now !== undefined) {
      const left = now.filter((m) => !taken.includes(m));
      if (left.length === 0) MISSED.delete(key);
      else MISSED.set(key, left);
    }
  }
  if (answer.block === false && answer.decision === "allow") return undefined;
  if (answer.block === false && answer.decision === "ask" && answer.approval && typeof answer.approval === "object") {
    return {
      requireApproval: {
        title: String(answer.approval.title || "openmorals asks before this step"),
        description: String(answer.approval.description || answer.message || "openmorals"),
        severity: answer.approval.severity === "critical" ? "critical" : "warning",
        allowedDecisions: ["allow-once", "deny"],
      },
    };
  }
  return { block: true, blockReason: typeof answer.message === "string" && answer.message !== "" ? answer.message : "blocked by openmorals" };
}

async function afterToolCall(event, ctx) {
  const answer = await consult({
    event: "after_tool_call",
    toolName: String(event && event.toolName),
    params: event && event.params ? event.params : null,
    toolCallId: (event && event.toolCallId) || null,
    sessionId: sessionOf(null, ctx),
    output: resultText(event && event.result),
    error: event && typeof event.error === "string" ? event.error : null,
    agentId: agentOf(ctx),
    cwd: PROJECT,
  });
  if (!delivered(answer)) remember(sessionOf(null, ctx), { event: "after_tool_call", toolName: String(event && event.toolName) });
}

async function llmOutput(event, ctx) {
  if (!event || !event.usage) return;
  const model = typeof event.resolvedRef === "string" && event.resolvedRef !== "" ? event.resolvedRef : typeof event.provider === "string" && typeof event.model === "string" ? event.provider + "/" + event.model : null;
  const session = sessionOf(event, ctx);
  const answer = await consult({ event: "llm_output", sessionId: session, model, usage: event.usage, cwd: PROJECT });
  if (!delivered(answer)) remember(session, { event: "llm_output" });
}

export default {
  id: "openmorals",
  name: "openmorals",
  description: "Asks before an agent deletes, force-pushes, deletes something online, leaks a secret or overspends its budget.",
  configSchema: { type: "object", additionalProperties: false, properties: {} },
  register(api) {
    api.on("before_tool_call", beforeToolCall, { timeoutMs: 30000 });
    api.on("after_tool_call", afterToolCall, { timeoutMs: 30000 });
    api.on("llm_output", llmOutput, { timeoutMs: 30000 });
  },
};
`;
}

export function openclawManifest(): string {
  return `${JSON.stringify({ id: 'openmorals', name: 'openmorals', description: 'openmorals policy hook: ask before risky tool calls', configSchema: { type: 'object', additionalProperties: false, properties: {} } }, null, 2)}\n`;
}

export function openclawPackageJson(): string {
  return `${JSON.stringify({ name: 'openmorals-openclaw-plugin', version: '1.0.0', private: true, type: 'module', description: 'Generated by openmorals init --agent openclaw', openclaw: { extensions: ['./index.js'] } }, null, 2)}\n`;
}

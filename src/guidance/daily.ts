/**
 * Daily guidance tiers (0.29.0). Everything here is text for the agent, rendered from the principles of the `daily` pack:
 * tier 0 (`render.ts`, the `daily` form), three activity skills, and the opt-in first-activity context the hook adds.
 * None of it changes a decision, and nothing is written or sent unless `openmorals init --pack daily` is run or
 * `guidance.first_activity` is switched on in the user-level file.
 */

export type SkillActivity = Exclude<Activity, 'always'>;

export interface DailyActivity {
  id: SkillActivity;
  /** The skill's folder and `name` (the Agent Skills format makes them equal). */
  skill: string;
  title: string;
  /** Always loaded by a host that lists skills; at most `DESCRIPTION_MAX_CHARS`. */
  description: string;
  /** Whether the skill carries the risk catalogue as `references/risks.md`. */
  references: boolean;
}

export const DESCRIPTION_MAX_CHARS = 160;
/** A skill body (and so a first-activity message), from the design review's estimate of ~270 tokens per activity (1,085 characters). */
export const SKILL_BODY_MAX_CHARS = 1100;
/** The risk catalogue the forms and email skills open only when a signal is in front of the agent (~2,000 tokens at most). */
export const REFERENCE_MAX_CHARS = 8000;
export { TIER0_MAX_CHARS };

export const DAILY_PACK = 'daily';

export const DAILY_ACTIVITIES: readonly DailyActivity[] = Object.freeze([
  { id: 'documents', skill: 'openmorals-documents', title: 'Writing or editing a document', description: 'Use when writing, editing, tidying or deleting documents such as notes, reports, .md, .docx or .txt files: keep existing text, ask before removing it.', references: false },
  { id: 'forms', skill: 'openmorals-forms', title: 'Filling in an online form', description: 'Use when filling in or submitting an online form, sign-in or checkout page: check the site, and which private details go in, before typing.', references: true },
  { id: 'email-and-links', skill: 'openmorals-email-and-links', title: 'Handling email and links', description: 'Use when reading, replying to, forwarding or sending email or messages, or opening a link or attachment: spot phishing and wrong recipients.', references: true },
]);

/** The line in a skill's README.md that marks the folder as written by openmorals, so `init` may replace it and nothing else. */
export const GENERATED_MARK = 'Generated by openmorals from packs/daily.yaml';

export type DailyRead = { ok: true; principles: Principle[]; source: string } | { ok: false; error: string };

/** A pack's principles in file order, read the way the hook reads the file (an invalid pack is refused, not rendered). */
export function readDailyPrinciples(text: string, source: string): DailyRead {
  const s = packSummary(text, source);
  if (!s.ok) return { ok: false, error: s.error };
  return { ok: true, principles: s.principles, source };
}

/** The shipped daily pack's principles. */
export function shippedDaily(): DailyRead {
  const t = readPackText(DAILY_PACK);
  if (!t.ok) return { ok: false, error: t.error };
  return readDailyPrinciples(t.text, t.file);
}

/** True when a pack carries guidance lines (what makes `init` write tier 0 and the skills). */
export function hasDailyGuidance(principles: readonly Principle[]): boolean {
  return principles.some((p) => p.guidance !== undefined);
}

function linesFor(principles: readonly Principle[], a: Activity): Principle[] {
  return principles.filter((p) => p.guidance !== undefined && (p.activities ?? []).includes(a));
}

/**
 * The model-facing body of one skill: a title, its lines, and (in a skill folder) the pointer to the risk list. The
 * first-activity message is the same text without the pointer, which names a file only a skill folder has.
 */
export function skillBody(principles: readonly Principle[], a: DailyActivity, pointer = true): string {
  const out = [`# ${a.title} (openmorals)`, '', ...linesFor(principles, a.id).map((p) => `- ${sanitize(p.guidance ?? '', 300)}`)];
  if (a.references && pointer) out.push('', 'If something looks wrong, read references/risks.md: common attacks and what to do.');
  return out.join('\n');
}

/** `SKILL.md`: the Agent Skills front matter (name, description) and the body. */
export function skillFile(principles: readonly Principle[], a: DailyActivity): string {
  return `---\nname: ${a.skill}\ndescription: ${JSON.stringify(a.description)}\n---\n\n${skillBody(principles, a)}\n`;
}

/** Characters / 4, rounded up: the estimate used throughout (no tokenizer is run; real counts differ by model). */
export function estimateTokens(chars: number): number {
  return Math.ceil(chars / 4);
}

/** The skill's human-facing header (`README.md`, which the agent does not load): advice only, and which guard checks which line. */
export function skillReadme(principles: readonly Principle[], a: DailyActivity): string {
  const body = skillBody(principles, a);
  const out: string[] = [];
  out.push(`# ${a.skill}: ${a.title}`);
  out.push('');
  out.push(`${GENERATED_MARK} (src/guidance/daily.ts); edits here are replaced. This file is for people; the agent reads SKILL.md.`);
  out.push('');
  out.push('**Advice only, not checked.** The lines in SKILL.md are guidance text for the agent. openmorals does not check that the agent follows them. Where a line is also checked, the guard named below checks it, and only as far as that guard reaches, on a host that calls openmorals before each action.');
  out.push('');
  out.push('| Line | Checked |');
  out.push('|---|---|');
  for (const p of linesFor(principles, a.id)) out.push(`| ${(p.guidance ?? '').replace(/\|/g, '\\|')} | ${p.checked_by !== undefined ? `checked by: ${p.checked_by.join(', ')}` : 'advice only, not checked'} |`);
  out.push('');
  out.push(`Measured size: description ${a.description.length} characters (about ${estimateTokens(a.description.length)} tokens, loaded whenever the host lists skills); body ${body.length} characters (about ${estimateTokens(body.length)} tokens, loaded when the skill is used)${a.references ? `; references/risks.md ${renderRisksReference().length} characters (about ${estimateTokens(renderRisksReference().length)} tokens, opened only when needed)` : ''}. Tokens are estimated as characters / 4.`);
  out.push('');
  out.push('Remove it by deleting this folder. See docs/daily.md in the openmorals package.');
  out.push('');
  return out.join('\n');
}

export interface RenderedFile {
  /** Relative to the folder skills are written under (`skills/` in the repository, `.claude/skills/` in a project). */
  path: string;
  text: string;
}

/** The three skills' files, relative to a skills folder. */
export function renderSkills(principles: readonly Principle[]): RenderedFile[] {
  const out: RenderedFile[] = [];
  for (const a of DAILY_ACTIVITIES) {
    out.push({ path: `${a.skill}/SKILL.md`, text: skillFile(principles, a) });
    out.push({ path: `${a.skill}/README.md`, text: skillReadme(principles, a) });
    if (a.references) out.push({ path: `${a.skill}/references/risks.md`, text: renderRisksReference() });
  }
  return out;
}

/** Every generated file of the repository: `skills/` and `docs/daily-risks.md`, from the shipped daily pack (scripts/render-daily.mjs writes them). */
export function renderRepoFiles(principles: readonly Principle[]): RenderedFile[] {
  return [...renderSkills(principles).map((f) => ({ path: `skills/${f.path}`, text: f.text })), { path: 'docs/daily-risks.md', text: renderRisksDoc() }];
}

export type TierZero = { ok: true; text: string } | { ok: false; error: string };

/** Tier 0 from a pack's principles, refused when there is none or when it is over `TIER0_MAX_CHARS`. */
export function tierZero(principles: readonly Principle[]): TierZero {
  const text = renderDailyGuidance(principles);
  if (text === null) return { ok: false, error: 'the pack has no always-on guidance line' };
  if (text.length > TIER0_MAX_CHARS) return { ok: false, error: `the always-on block is ${text.length} characters, over ${TIER0_MAX_CHARS}` };
  return { ok: true, text };
}

function toolWords(tool: string): string[] {
  return tool
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((w) => w !== '');
}

/** Words in a tool's name that say it works on mail or messages (the outbound guard's send words are read too). */
const MAIL_WORDS = new Set(['mail', 'email', 'gmail', 'outlook', 'inbox', 'imap', 'smtp', 'message', 'messages']);

/**
 * The activities one call belongs to, from what the PreToolUse hook already sees (0.29.0): a write to a path the document
 * guard counts as a document is `documents`; a tool call the outbound guard reads as typing into or submitting a form is
 * `forms`; a tool call whose name says it sends, replies, forwards or shares, opens a page in a browser, or works on mail
 * or messages is `email-and-links`. Agent-to-agent message tools are none of these. Decides nothing.
 */
export function callActivities(actions: readonly Action[], bylaws: Bylaws, where: Where): SkillActivity[] {
  const found = new Set<SkillActivity>();
  const agentTools = MESSAGE_TOOLS['claude-code'];
  for (const a of actions) {
    if (a.kind === 'write') {
      const abs = documentPath(a.path, where);
      if (abs !== null && documentShaped(abs, bylaws, where)) found.add('documents');
      continue;
    }
    if (a.kind !== 'other' || Object.prototype.hasOwnProperty.call(agentTools, a.tool)) continue;
    if (entryTool(a.tool, a.leaves ?? [])) found.add('forms');
    if (isSendTool(a.tool) || isNavigateTool(a.tool) || toolWords(a.tool).some((w) => MAIL_WORDS.has(w))) found.add('email-and-links');
  }
  return DAILY_ACTIVITIES.map((x) => x.id).filter((id) => found.has(id));
}

/** The first-activity message for the activities not yet guided in this session, or null when there is nothing to send. */
export function firstActivityText(principles: readonly Principle[], activities: readonly SkillActivity[]): string | null {
  const parts = DAILY_ACTIVITIES.filter((a) => activities.includes(a.id))
    .map((a) => skillBody(principles, a, false));
  return parts.length === 0 ? null : parts.join('\n\n');
}

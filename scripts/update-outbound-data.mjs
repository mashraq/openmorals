#!/usr/bin/env node
// Regenerates the two data files the outbound guard bundles (0.20.0) from local copies of their sources:
//   node scripts/update-outbound-data.mjs <public_suffix_list.dat> <confusables.txt>
// Sources: https://publicsuffix.org/list/public_suffix_list.dat (MPL-2.0) and
// https://www.unicode.org/Public/security/latest/confusables.txt (Unicode License v3). This script reads only the two
// files named and writes only src/outbound/data/public-suffix.ts and src/outbound/data/confusables.ts; it opens no
// network connection (download the files yourself first).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { domainToASCII } from 'node:url';

if (process.argv.includes('--help') || process.argv.includes('-h') || process.argv.length < 4) {
  console.log('usage: node scripts/update-outbound-data.mjs <public_suffix_list.dat> <confusables.txt>');
  process.exit(process.argv.length < 4 && !process.argv.includes('--help') && !process.argv.includes('-h') ? 2 : 0);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pslText = readFileSync(process.argv[2], 'utf8');
const confText = readFileSync(process.argv[3], 'utf8');

const version = /^\/\/ VERSION: (\S+)/m.exec(pslText)?.[1] ?? 'unknown';
const commit = /^\/\/ COMMIT: (\S+)/m.exec(pslText)?.[1] ?? 'unknown';
const groups = new Map();
let count = 0;
for (const raw of pslText.split('\n')) {
  const line = raw.trim();
  if (line === '' || line.startsWith('//')) continue;
  let prefix = '';
  let body = line;
  if (body.startsWith('!')) {
    prefix = '!';
    body = body.slice(1);
  } else if (body.startsWith('*.')) {
    prefix = '*.';
    body = body.slice(2);
  }
  const ascii = domainToASCII(body);
  if (ascii === '') throw new Error(`cannot convert rule ${line}`);
  const labels = ascii.split('.');
  const tld = labels.pop();
  const rest = `${prefix}${labels.join('.')}`;
  if (!groups.has(tld)) groups.set(tld, []);
  groups.get(tld).push(rest);
  count++;
}
const pslLines = [...groups.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([tld, rests]) => `${tld}:${[...new Set(rests)].sort().join(',')}`);
const pslOut = `// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy of the MPL was not
// distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.
//
// The Public Suffix List (https://publicsuffix.org/list/public_suffix_list.dat), VERSION ${version}, COMMIT ${commit},
// ICANN and private sections, ${count} rules, each converted to its ASCII (punycode) form and grouped by its last label:
// one line per top-level label, "<label>:<rest>,<rest>,..." where a rest is the rule without its last label (empty for
// the label itself, "*." for a wildcard, "!" for an exception). Generated by scripts/update-outbound-data.mjs; do not
// edit by hand.

/** The list's version line. */
export const PUBLIC_SUFFIX_VERSION: string = ${JSON.stringify(version)};

/** How many rules the list holds. */
export const PUBLIC_SUFFIX_RULES: number = ${count};

export const PUBLIC_SUFFIX_DATA: string = ${JSON.stringify(pslLines.join('\n'))};
`;
writeFileSync(join(root, 'src/outbound/data/public-suffix.ts'), pslOut);

const date = /^# Date: (.+)$/m.exec(confText)?.[1]?.trim() ?? 'unknown';
const pairs = [];
for (const line of confText.split('\n')) {
  const m = /^([0-9A-F]+) ;\t([0-9A-F ]+);/.exec(line);
  if (m === null) continue;
  const src = String.fromCodePoint(parseInt(m[1], 16));
  const dst = m[2].trim().split(' ').map((h) => String.fromCodePoint(parseInt(h, 16))).join('').toLowerCase();
  if (!/^[a-z0-9-]+$/.test(dst)) continue;
  if (src === dst) continue;
  pairs.push(`${src}${dst}`);
}
const confOut = `// The confusables subset the outbound guard uses for UTS #39 skeletons (0.20.0): every single-character entry of
// Unicode confusables.txt (https://www.unicode.org/Public/security/latest/confusables.txt, ${date}) whose prototype is
// ASCII letters, digits or hyphens after lower-casing, ${pairs.length} entries. Each entry is the source character followed
// by its prototype; entries are separated by U+001F. Generated by scripts/update-outbound-data.mjs; do not edit by hand.
//
// Copyright © 1991-2026 Unicode, Inc. Unicode and the Unicode Logo are registered trademarks of Unicode, Inc. in the
// United States and other countries. Distributed under the Unicode License v3 (https://www.unicode.org/license.txt);
// see NOTICE.

/** The date line of the confusables file the subset was taken from. */
export const CONFUSABLES_DATE: string = ${JSON.stringify(date)};

export const CONFUSABLES_DATA: string = ${JSON.stringify(pairs.join('\u001f'))};
`;
writeFileSync(join(root, 'src/outbound/data/confusables.ts'), confOut);
console.log(`public suffix list: ${count} rules in ${pslLines.length} groups; confusables: ${pairs.length} entries`);
